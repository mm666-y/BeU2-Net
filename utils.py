class myRandomRotation:
    def __init__(self, p=0.5, degree=[0,360]):
        self.angle = random.uniform(degree[0], degree[1])
        self.p = p
    def __call__(self, data):
        image, mask,edge = data
        if random.random() < self.p: return TF.rotate(image,self.angle), TF.rotate(mask,self.angle),TF.rotate(edge,self.angle)
        else: return image, mask, edge




