class myRandomHorizontalFlip:
    def __init__(self, p=0.5):
        self.p = p
    def __call__(self, data):
        image, mask,edge = data
        if random.random() < self.p: return TF.hflip(image), TF.hflip(mask), TF.hflip(edge)
        else: return image, mask,  edge
            

